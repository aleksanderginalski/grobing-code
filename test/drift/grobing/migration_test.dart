          surname: 'Wymyślony',
          bio: 'Kowal, wymyślony do testów.',
          bioSource: 'notatki',
          isLiving: 0,
        ),
        v2.PersonsData(
          id: 2,
          givenNames: 'Anna',
          surname: 'Wymyślona',
          birthSurname: 'Zmyślona',
          isLiving: 0,
        ),
      ];
      const List<v2.CemeteriesData> cemeteries = [
        v2.CemeteriesData(
          id: 1,
          name: 'Cmentarz Wymyślony',
          locality: 'Miejscowość Testowa',
          centerLat: 51,
          centerLon: 20,
        ),
      ];
      const List<v2.GravesData> graves = [
        v2.GravesData(id: 1, cemeteryId: 1),
        v2.GravesData(id: 2, cemeteryId: 1, sector: 'B', row: '4', plot: '12'),
