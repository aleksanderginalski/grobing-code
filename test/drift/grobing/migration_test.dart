      ];
      const List<v2.BurialsData> burials = [
        v2.BurialsData(id: 1, personId: 1, graveId: 1),
        v2.BurialsData(id: 2, personId: 2, graveId: 1),
      ];
      const List<v2.AssertionsData> claims = [
        v2.AssertionsData(
          id: 1,
          eventId: 1,
          sourceKind: 'notes',
          status: 'claimed',
          recordedAt: 1791273600,
