      ];

      await verifier.testWithDataIntegrity(
        oldVersion: 2,
        newVersion: 3,
        createOld: v2.DatabaseAtV2.new,
        createNew: v3.DatabaseAtV3.new,
        openTestedDatabase: GrobingDatabase.new,
        createItems: (batch, oldDb) {
          batch.insertAll(oldDb.persons, persons);
          batch.insertAll(oldDb.cemeteries, cemeteries);
          batch.insertAll(oldDb.graves, graves);
