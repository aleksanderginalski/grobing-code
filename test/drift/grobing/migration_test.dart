          same(await newDb.select(newDb.burials).get(), burials);
          same(await newDb.select(newDb.assertions).get(), claims);

          // Graves: the same values, and the new name empty — never derived from the people.
          final List<v3.GravesData> migrated = await newDb
              .select(newDb.graves)
              .get();
          expect(migrated.map((g) => g.name), everyElement(equals(null)));
          expect(
            migrated.map((g) => g.toJson()..remove('name')),
            graves.map((g) => g.toJson()),
          );
        },
      );
    },
  );

  test(
    'ISSUE-017 F2 — v3 to v4 keeps every row; each person photo becomes a link of that person in the order '
    'of its id (the first stays the profile), the grave keeps its photo, no reference breaks',
    () async {
      const List<v3.PersonsData> persons = [
        v3.PersonsData(
          id: 1,
          givenNames: 'Jan',
          surname: 'Wymyślony',
          isLiving: 0,
        ),
        v3.PersonsData(
          id: 2,
          givenNames: 'Anna',
          surname: 'Wymyślona',
          isLiving: 0,
        ),
        v3.PersonsData(
          id: 3,
          givenNames: 'Józef',
          surname: 'Wymyślony',
          isLiving: 0,
        ),
      ];
      const List<v3.CemeteriesData> cemeteries = [
        v3.CemeteriesData(id: 1, name: 'Cmentarz Wymyślony'),
      ];
      const List<v3.GravesData> graves = [
        v3.GravesData(id: 1, cemeteryId: 1, name: 'Grób Wymyślonych'),
      ];
      // Interleaved ids: Anna's photos are 2 and 5, so her order comes from the id, not the insert batch.
      const List<v3.MediaData> media = [
        v3.MediaData(id: 1, relativePath: 'groby/1/nagrobek.jpg', graveId: 1),
        v3.MediaData(id: 2, relativePath: 'osoby/anna-a.jpg', personId: 2),
        v3.MediaData(id: 3, relativePath: 'osoby/jan-a.jpg', personId: 1),
        v3.MediaData(id: 5, relativePath: 'osoby/anna-b.jpg', personId: 2),
      ];

      await verifier.testWithDataIntegrity(
        oldVersion: 3,
        newVersion: 4,
        createOld: v3.DatabaseAtV3.new,
        createNew: v4.DatabaseAtV4.new,
        openTestedDatabase: GrobingDatabase.new,
        createItems: (batch, oldDb) {
          batch.insertAll(oldDb.persons, persons);
          batch.insertAll(oldDb.cemeteries, cemeteries);
          batch.insertAll(oldDb.graves, graves);
          batch.insertAll(oldDb.media, media);
        },
        validateItems: (newDb) async {
          expect(
            (await newDb.select(newDb.persons).get()).map((p) => p.toJson()),
            persons.map((p) => p.toJson()),
          );
          // Every media row and id stays (a v3 restore counts them), without person_id now.
          expect(
            (await newDb.select(newDb.media).get()).map(
              (m) => (m.id, m.relativePath, m.graveId),
            ),
            media.map((m) => (m.id, m.relativePath, m.graveId)),
          );
          final List<v4.PersonMediaData> links =
              await (newDb.select(newDb.personMedia)..orderBy([
                    (l) => OrderingTerm.asc(l.personId),
                    (l) => OrderingTerm.asc(l.position),
                  ]))
                  .get();
          expect(links.map((l) => (l.personId, l.mediaId, l.position)), [
            (1, 3, 0),
            (2, 2, 0),
            (2, 5, 1),
          ]);
          // Józef had no photo and has no link; the grave's photo has none either.
          expect(
            links.where((l) => l.personId == 3 || l.mediaId == 1),
            isEmpty,
          );
          expect(
            await newDb.customSelect('PRAGMA foreign_key_check').get(),
            isEmpty,
          );
        },
      );
    },
  );

  test(
    'ISSUE-018 F2 — v4 to v5 keeps every row, link and position; every link has no crop, so every profile '
    'circle shows the middle as before; no reference breaks',
    () async {
      const List<v4.PersonsData> persons = [
        v4.PersonsData(
          id: 1,
          givenNames: 'Jan',
          surname: 'Wymyślony',
          isLiving: 0,
        ),
        v4.PersonsData(
          id: 2,
          givenNames: 'Anna',
          surname: 'Wymyślona',
          isLiving: 0,
        ),
      ];
      const List<v4.CemeteriesData> cemeteries = [
        v4.CemeteriesData(id: 1, name: 'Cmentarz Wymyślony'),
      ];
      const List<v4.GravesData> graves = [
        v4.GravesData(id: 1, cemeteryId: 1, name: 'Grób Wymyślonych'),
      ];
      // A gravestone, a photo shared by both (Jan's profile, Anna's second) and Anna's own profile.
      const List<v4.MediaData> media = [
        v4.MediaData(id: 1, relativePath: 'groby/1/nagrobek.jpg', graveId: 1),
        v4.MediaData(id: 2, relativePath: 'zdjecia/slub.jpg'),
        v4.MediaData(id: 3, relativePath: 'zdjecia/anna.jpg'),
      ];
      const List<v4.PersonMediaData> links = [
        v4.PersonMediaData(personId: 1, mediaId: 2, position: 0),
        v4.PersonMediaData(personId: 2, mediaId: 3, position: 0),
        v4.PersonMediaData(personId: 2, mediaId: 2, position: 1),
      ];

      await verifier.testWithDataIntegrity(
        oldVersion: 4,
        newVersion: 5,
        createOld: v4.DatabaseAtV4.new,
        createNew: v5.DatabaseAtV5.new,
        openTestedDatabase: GrobingDatabase.new,
        createItems: (batch, oldDb) {
          batch.insertAll(oldDb.persons, persons);
          batch.insertAll(oldDb.cemeteries, cemeteries);
          batch.insertAll(oldDb.graves, graves);
          batch.insertAll(oldDb.media, media);
          batch.insertAll(oldDb.personMedia, links);
        },
        validateItems: (newDb) async {
          expect(
            (await newDb.select(newDb.persons).get()).map((p) => p.toJson()),
            persons.map((p) => p.toJson()),
          );
          expect(
            (await newDb.select(newDb.media).get()).map(
              (m) => (m.id, m.relativePath, m.graveId),
            ),
            media.map((m) => (m.id, m.relativePath, m.graveId)),
          );
          final List<v5.PersonMediaData> after =
              await (newDb.select(newDb.personMedia)..orderBy([
                    (l) => OrderingTerm.asc(l.personId),
                    (l) => OrderingTerm.asc(l.position),
                  ]))
                  .get();
          expect(
            after.map(
              (l) => (
                l.personId,
                l.mediaId,
                l.position,
                l.cropLeft,
                l.cropTop,
                l.cropWidth,
                l.cropHeight,
              ),
            ),
            [
              (1, 2, 0, null, null, null, null),
              (2, 3, 0, null, null, null, null),
              (2, 2, 1, null, null, null, null),
            ],
          );
          expect(
            await newDb.customSelect('PRAGMA foreign_key_check').get(),
            isEmpty,
          );
        },
      );
    },
  );
}
